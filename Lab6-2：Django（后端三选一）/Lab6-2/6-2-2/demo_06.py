# 定义变量，存储数据 Hello World (使用单引号 ' )
a = 'Hello World'
# 打印变量
print(a)
# 打印变量类型
print(type(a))


# 定义变量，存储数据 Hello World (使用双引号 " )
b = "Hello World"
# 打印变量
print(b)
# 打印变量类型
print(type(b))


# 定义变量，存储数据 Hello World (使用三引号( ''' 或 """ ))
c = '''Hello World'''
# 打印变量
print(c)
# 打印变量类型
print(type(c))

